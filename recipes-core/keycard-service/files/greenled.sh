#!/bin/sh

case "$1" in
  "green"|"1")
    # Green LED
    i2cset -f -y 2 0x30 0x00 0xc0 0x3f 0x00 0xff 0x00 0xaf 0xaf 0xaf 0x61 i
    ;;
  "red")
    # Red LED
    i2cset -f -y 2 0x30 0x00 0xc0 0x3f 0x00 0x00 0xff 0xaf 0xaf 0xaf 0x61 i
    ;;
  "amber")
    # Amber LED
    i2cset -f -y 2 0x30 0x00 0xc0 0x3f 0xff 0x00 0x00 0xaf 0xaf 0xaf 0x61 i
    ;;
  *)
    # Turn off LED
    i2cset -f -y 2 0x30 0x00 0x40 0x3f 0x00 0x00 0x00 0x32 0x32 0x32 0x01 i
    ;;
esac
